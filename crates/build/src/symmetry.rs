//! Point groups: which symmetry a structure has, which higher ones it is
//! close to (with the largest atom move each would need), and making one of
//! them exact (`symmetrize`).
//!
//! The method, in short:
//! 1. Atoms are taken about their centroid (a symmetry operation permutes
//!    like atoms, so it fixes the centroid of a symmetric structure).
//! 2. Candidate directions: the principal axes, the atoms, and, within each
//!    shell of like atoms at the same distance from the center, the sums,
//!    differences and cross products of pairs and the sums and normals of
//!    triples (ring axes, the C3 and C5 axes of cubic and icosahedral
//!    molecules).
//! 3. Elements: along each direction, a mirror plane, rotations C2..C8 and
//!    improper rotations S3..S12, kept when every atom lands on a like atom
//!    within `FIND_TOLERANCE`; and the inversion.
//! 4. Groups: generated by one element, two (their angle first snapped to
//!    the nearest angle a finite point group allows, so the group closes
//!    exactly), and those with the inversion added. Each is named by the
//!    Schoenflies rules and checked by symmetrizing: its displacement is the
//!    largest move of an atom.
//! 5. Kept: the groups not contained in a larger one that is as close.
//!
//! Linear molecules (C∞v, D∞h) are handled apart.

use std::collections::HashMap;

use glam::{DMat3, DQuat, DVec3, Vec3};

/// How far (angstrom) an operation may move atoms off like atoms and still
/// count as an element: the largest displacement listed.
pub const FIND_TOLERANCE: f64 = 0.3;

/// The tolerance the programs use (Q-Chem 1e-5, ORCA 1e-4 bohr): within it
/// a structure "has" a group as a quantum chemistry program would see it.
pub const PROGRAM_TOLERANCE: f64 = 1e-4;

/// A symmetry element, for drawing it: all pass through the center.
#[derive(Debug, Clone, PartialEq)]
pub enum Element {
    /// A proper rotation axis of `order` (0: infinite, a linear molecule).
    Axis { direction: DVec3, order: u32 },
    /// A mirror plane with this normal.
    Plane { normal: DVec3 },
    /// The inversion center.
    Inversion,
}

/// A point group a structure is close to.
#[derive(Debug, Clone)]
pub struct Candidate {
    /// Schoenflies name: "C2v", "D5h", "Oh", "C∞v".
    pub label: String,
    /// Number of operations (0 for the linear groups).
    pub order: usize,
    /// The largest move of an atom that symmetrizing to it needs, angstrom.
    pub displacement: f64,
    /// Its elements, for drawing (axes with their highest order, planes,
    /// the inversion).
    pub elements: Vec<Element>,
    /// The symmetrized positions.
    symmetric: Vec<Vec3>,
    /// Its operations about the analysis's center, and where each sends
    /// every atom (empty for the linear groups).
    pub operations: Vec<DMat3>,
    pub permutations: Vec<Vec<usize>>,
}

impl Candidate {
    /// The positions with this group exact.
    pub fn symmetrized(&self) -> &[Vec3] {
        &self.symmetric
    }

    /// The main axis: of the highest order (infinite for linear
    /// molecules), and of those the one lying in the most mirror planes (so
    /// D2d's S4 axis, not a perpendicular C2). `None` without an axis.
    pub fn main_axis(&self) -> Option<DVec3> {
        let axes: Vec<(DVec3, u32)> = self.elements.iter().filter_map(|e| if let Element::Axis { direction, order } = e { Some((*direction, *order)) } else { None }).collect();
        let key = |o: u32| if o == 0 { u32::MAX } else { o };
        let top = axes.iter().map(|(_, o)| key(*o)).max()?;
        let in_planes = |a: DVec3| self.elements.iter().filter(|e| matches!(e, Element::Plane { normal } if normal.dot(a).abs() < 1e-3)).count();
        axes.iter().filter(|(_, o)| key(*o) == top).map(|(a, _)| *a).max_by_key(|a| in_planes(*a))
    }

    /// A short description of its main elements, to tell apart candidates
    /// of the same group: "C2 along (0.00, 0.00, 1.00)".
    pub fn describe(&self) -> String {
        let main = self.elements.iter().filter_map(|e| match e {
            Element::Axis { order, .. } => Some(*order),
            _ => None,
        });
        let top = main.max().unwrap_or(0);
        let axes = self.elements.iter().filter(|e| matches!(e, Element::Axis { order, .. } if *order == top && top > 0)).count();
        let planes = self.elements.iter().filter(|e| matches!(e, Element::Plane { .. })).count();
        let mut parts = Vec::new();
        if top > 0 {
            parts.push(format!("{axes} C{top} {}", if axes == 1 { "axis" } else { "axes" }));
        }
        if planes > 0 {
            parts.push(format!("{planes} plane{}", if planes == 1 { "" } else { "s" }));
        }
        if self.elements.contains(&Element::Inversion) {
            parts.push("inversion".to_string());
        }
        parts.join(", ")
    }
}

/// What `analyze` found: the groups the structure is close to, highest
/// first, and the center the elements pass through.
#[derive(Debug, Clone)]
pub struct Analysis {
    pub center: DVec3,
    pub candidates: Vec<Candidate>,
}

impl Analysis {
    /// The highest group within `tolerance` (largest move, angstrom).
    pub fn group_within(&self, tolerance: f64) -> &Candidate {
        self.candidates.iter().filter(|c| c.displacement <= tolerance).max_by(|a, b| rank(a).cmp(&rank(b))).unwrap_or(&self.candidates[self.candidates.len() - 1])
    }

    /// The highest group above `current` within `tolerance` (largest
    /// move, angstrom), if any: the symmetry the structure is really close
    /// to (a distorted ammonia: C3v, rather than one of its mirror planes).
    pub fn highest_above(&self, current: &Candidate, tolerance: f64) -> Option<&Candidate> {
        self.candidates
            .iter()
            .filter(|c| rank(c) > rank(current) && c.displacement <= tolerance)
            .max_by(|a, b| rank(a).cmp(&rank(b)).then(b.displacement.total_cmp(&a.displacement)))
    }
}

/// Orders groups by size, the linear ones above all finite ones.
fn rank(c: &Candidate) -> usize {
    if c.order == 0 { if c.label == "D∞h" { 1_000_001 } else { 1_000_000 } } else { c.order }
}

/// The groups a structure is close to.
pub fn analyze(atomic_numbers: &[u32], positions: &[Vec3]) -> Analysis {
    let n = positions.len();
    let p: Vec<DVec3> = positions.iter().map(|v| v.as_dvec3()).collect();
    let center = if n == 0 { DVec3::ZERO } else { p.iter().copied().sum::<DVec3>() / n as f64 };
    let q: Vec<DVec3> = p.iter().map(|v| *v - center).collect();
    let mut candidates = vec![Candidate {
        label: "C1".into(),
        order: 1,
        displacement: 0.0,
        elements: Vec::new(),
        symmetric: positions.to_vec(),
        operations: vec![DMat3::IDENTITY],
        permutations: vec![(0..n).collect()],
    }];
    if n < 2 {
        return Analysis { center, candidates };
    }
    // A nearly linear molecule can still have exact finite symmetry (three
    // atoms are always in a plane): both kinds are looked for.
    if let Some(linear) = linear_candidates(atomic_numbers, &q, center) {
        candidates.extend(linear);
    }
    candidates.extend(finite_candidates(atomic_numbers, &q, center));
    prune(&mut candidates);
    candidates.sort_by(|a, b| rank(b).cmp(&rank(a)).then(a.displacement.total_cmp(&b.displacement)));
    Analysis { center, candidates }
}

// ---------------------------------------------------------------- orientation

/// The positions in a standard orientation for `group` (one of the
/// analysis's candidates, usually the structure's own group): the center of
/// nuclear charge at the origin (as Gaussian), the main rotation axis along
/// z (for Cs, the plane's normal; without either, the principal axis whose
/// moment stands apart from the other two), and x along a C2 axis perpendicular to it, or in a
/// mirror plane containing it, or along a principal axis.
pub fn standard_orientation(atomic_numbers: &[u32], positions: &[Vec3], group: &Candidate) -> Vec<Vec3> {
    let (rotation, center) = standard_frame(atomic_numbers, positions, group);
    positions.iter().map(|v| (rotation * (v.as_dvec3() - center)).as_vec3()).collect()
}

/// The motion `standard_orientation` applies: new = rotation (old - center).
pub fn standard_frame(atomic_numbers: &[u32], positions: &[Vec3], group: &Candidate) -> (DMat3, DVec3) {
    let p: Vec<DVec3> = positions.iter().map(|v| v.as_dvec3()).collect();
    let charge: f64 = atomic_numbers.iter().map(|&z| f64::from(z)).sum::<f64>().max(1e-9);
    let center = p.iter().zip(atomic_numbers).map(|(v, &z)| *v * f64::from(z)).sum::<DVec3>() / charge;
    let q: Vec<DVec3> = p.iter().map(|v| *v - center).collect();
    let principal = principal_axes(&q);
    let moment = |a: DVec3| q.iter().map(|v| (*v - a * v.dot(a)).length_squared()).sum::<f64>();
    let axes: Vec<(DVec3, u32)> = group.elements.iter().filter_map(|e| if let Element::Axis { direction, order } = e { Some((*direction, *order)) } else { None }).collect();
    let planes: Vec<DVec3> = group.elements.iter().filter_map(|e| if let Element::Plane { normal } = e { Some(*normal) } else { None }).collect();
    let main = group
        .main_axis()
        .or_else(|| planes.first().copied())
        .unwrap_or_else(|| {
            // The principal axis whose moment stands apart from the other
            // two (a symmetric top's unique axis).
            let m: Vec<f64> = principal.iter().map(|a| moment(*a)).collect();
            let apart = |i: usize| (0..3).filter(|&j| j != i).map(|j| (m[i] - m[j]).abs()).fold(f64::MAX, f64::min);
            principal[(0..3).max_by(|&a, &b| apart(a).total_cmp(&apart(b))).unwrap()]
        });
    let z = main.normalize();
    // The part of `v` across z, if it has one (not just rounding noise).
    let perpendicular = |v: DVec3| Some(v - z * v.dot(z)).filter(|w| w.length() > 1e-6).map(DVec3::normalize);
    let x = axes
        .iter()
        .filter(|(a, o)| *o == 2 && a.dot(z).abs() < 1e-3)
        .find_map(|(a, _)| perpendicular(*a))
        .or_else(|| planes.iter().filter(|n| n.dot(z).abs() < 1e-3).find_map(|n| perpendicular(n.cross(z))))
        .or_else(|| principal.iter().filter_map(|a| perpendicular(*a)).max_by(|a, b| moment(*a).total_cmp(&moment(*b))))
        .unwrap_or_else(|| any_perpendicular(z));
    let y = z.cross(x);
    // Rows x, y, z: a point's new coordinates are its components along them.
    (DMat3::from_cols(x, y, z).transpose(), center)
}

// ---------------------------------------------------------------- linear

/// C∞v and D∞h, when every atom lies within `FIND_TOLERANCE` of one line.
fn linear_candidates(z: &[u32], q: &[DVec3], center: DVec3) -> Option<Vec<Candidate>> {
    let axis = principal_axes(q).into_iter().max_by(|a, b| spread(q, *a).total_cmp(&spread(q, *b)))?;
    if q.iter().any(|v| (*v - axis * v.dot(axis)).length() > FIND_TOLERANCE) {
        return None;
    }
    let on_axis: Vec<DVec3> = q.iter().map(|v| axis * v.dot(axis)).collect();
    let moved = |new: &[DVec3]| new.iter().zip(q).map(|(a, b)| a.distance(*b)).fold(0.0, f64::max);
    let to_vec3 = |v: &[DVec3]| v.iter().map(|w| (*w + center).as_vec3()).collect::<Vec<_>>();
    let mut out = vec![Candidate {
        label: "C∞v".into(),
        order: 0,
        displacement: moved(&on_axis),
        elements: vec![Element::Axis { direction: axis, order: 0 }],
        symmetric: to_vec3(&on_axis),
        operations: Vec::new(),
        permutations: Vec::new(),
    }];
    // D∞h: the inversion as well (each atom paired with a like atom at the
    // opposite position, or at the center).
    if let Some((perm, _)) = image_map(z, &on_axis, &(-DMat3::IDENTITY), FIND_TOLERANCE * 2.0) {
        let both: Vec<DVec3> = (0..q.len()).map(|i| (on_axis[i] - on_axis[perm[i]]) / 2.0).collect();
        out.push(Candidate {
            label: "D∞h".into(),
            order: 0,
            displacement: moved(&both),
            elements: vec![Element::Axis { direction: axis, order: 0 }, Element::Inversion],
            symmetric: to_vec3(&both),
            operations: Vec::new(),
            permutations: Vec::new(),
        });
    }
    Some(out)
}

fn spread(q: &[DVec3], axis: DVec3) -> f64 {
    q.iter().map(|v| v.dot(axis).powi(2)).sum()
}

// ---------------------------------------------------------------- finite

/// An element found: its matrix, and what it is.
#[derive(Clone)]
struct Found {
    matrix: DMat3,
    /// Axis or plane normal; zero for the inversion.
    direction: DVec3,
    /// What kind: 0 plane, n > 0 rotation Cn, n < 0 improper S|n|.
    kind: i32,
    /// How far the atoms land from like atoms, angstrom.
    miss: f64,
}

/// Adds an element unless one of the same kind lies within ~6 degrees: of
/// those, the one that maps the atoms most closely is kept. (With a
/// tolerance of tenths of an angstrom, an axis a few degrees off still
/// passes; one element per true element keeps the groups few.)
fn keep_best(found: &mut Vec<Found>, new: Found) {
    if let Some(existing) = found.iter_mut().find(|f| f.kind == new.kind && f.direction.dot(new.direction).abs() > 0.9945) {
        if new.miss < existing.miss {
            *existing = new;
        }
    } else {
        found.push(new);
    }
}

fn finite_candidates(z: &[u32], q: &[DVec3], center: DVec3) -> Vec<Candidate> {
    let directions = candidate_directions(z, q);
    let mut found: Vec<Found> = Vec::new();
    let inversion = -DMat3::IDENTITY;
    let has_inversion = image_map(z, q, &inversion, FIND_TOLERANCE).is_some();
    if has_inversion {
        found.push(Found { matrix: inversion, direction: DVec3::ZERO, kind: i32::MAX, miss: 0.0 });
    }
    for &u in &directions {
        let plane = reflection(u);
        if let Some((_, miss)) = image_map(z, q, &plane, FIND_TOLERANCE) {
            keep_best(&mut found, Found { matrix: plane, direction: u, kind: 0, miss });
        }
        let proper: Vec<(u32, DMat3, f64)> = (2..=8u32).filter_map(|n| {
            let m = rotation(u, n);
            image_map(z, q, &m, FIND_TOLERANCE).map(|(_, miss)| (n, m, miss))
        }).collect();
        let improper: Vec<(u32, DMat3, f64)> = (3..=12u32).filter_map(|n| {
            let m = reflection(u) * rotation(u, n);
            image_map(z, q, &m, FIND_TOLERANCE).map(|(_, miss)| (n, m, miss))
        }).collect();
        for (n, m, miss) in plausible_orders(proper) {
            keep_best(&mut found, Found { matrix: m, direction: u, kind: n as i32, miss });
        }
        for (n, m, miss) in plausible_orders(improper) {
            keep_best(&mut found, Found { matrix: m, direction: u, kind: -(n as i32), miss });
        }
    }

    // Groups from one or two generators (and with the inversion added).
    let mut groups: Vec<Vec<DMat3>> = Vec::new();
    let add = |gens: Vec<DMat3>, groups: &mut Vec<Vec<DMat3>>| {
        if let Some(group) = closure(&gens) {
            groups.push(group);
        }
    };
    for (a, fa) in found.iter().enumerate() {
        add(vec![fa.matrix], &mut groups);
        if has_inversion {
            add(vec![fa.matrix, inversion], &mut groups);
        }
        for fb in &found[a + 1..] {
            let Some(b) = snapped(fa, fb) else { continue };
            add(vec![fa.matrix, b], &mut groups);
            if has_inversion {
                add(vec![fa.matrix, b, inversion], &mut groups);
            }
        }
    }

    // Each group checked by symmetrizing; permutations cached by operation.
    // Groups that are nearly the same (same operations to 1e-3) count once:
    // the closest is kept.
    let mut maps: HashMap<[i64; 9], Option<Vec<usize>>> = HashMap::new();
    let mut best: HashMap<Vec<[i64; 9]>, usize> = HashMap::new();
    let mut out: Vec<Candidate> = Vec::new();
    for group in groups {
        let perms: Option<Vec<Vec<usize>>> = group
            .iter()
            .map(|m| maps.entry(rounded(m)).or_insert_with(|| image_map(z, q, m, FIND_TOLERANCE * 1.5).map(|(perm, _)| perm)).clone())
            .collect();
        let Some(perms) = perms else { continue };
        let symmetric: Vec<DVec3> = (0..q.len())
            .map(|i| group.iter().zip(&perms).map(|(m, perm)| m.transpose() * q[perm[i]]).sum::<DVec3>() / group.len() as f64)
            .collect();
        let displacement = symmetric.iter().zip(q).map(|(a, b)| a.distance(*b)).fold(0.0, f64::max);
        if displacement > FIND_TOLERANCE {
            continue;
        }
        let (label, elements) = classify(&group);
        let candidate = Candidate {
            label,
            order: group.len(),
            displacement,
            elements,
            symmetric: symmetric.iter().map(|v| (*v + center).as_vec3()).collect(),
            operations: group.clone(),
            permutations: perms,
        };
        let key = group_key(&group);
        match best.get(&key) {
            Some(&k) if out[k].displacement <= displacement => {}
            Some(&k) => out[k] = candidate,
            None => {
                best.insert(key, out.len());
                out.push(candidate);
            }
        }
    }
    out
}

/// Of the orders that passed about one axis, those not beaten by another
/// that maps the atoms more closely and neither divides nor is divided by
/// it: with a loose tolerance an S9 or S11 passes next to a true S10, only
/// a few degrees off.
fn plausible_orders(passed: Vec<(u32, DMat3, f64)>) -> Vec<(u32, DMat3, f64)> {
    passed
        .iter()
        .filter(|(n, _, miss)| !passed.iter().any(|(m, _, other)| other < miss && n % m != 0 && m % n != 0))
        .cloned()
        .collect()
}

/// Keeps the candidates that no larger group, as close or closer and
/// containing all their elements, makes redundant; and of identical ones
/// (same group, same elements) the closest.
fn prune(candidates: &mut Vec<Candidate>) {
    // Largest and closest first, each compared with those kept so far: what
    // would make a candidate redundant is kept itself, or made redundant by
    // something kept.
    candidates.sort_by(|a, b| rank(b).cmp(&rank(a)).then(a.displacement.total_cmp(&b.displacement)));
    let mut kept: Vec<Candidate> = Vec::new();
    for a in candidates.drain(..) {
        let redundant = kept.iter().any(|b| {
            let larger = rank(b) > rank(&a) && b.displacement <= a.displacement + 1e-6 && contains(b, &a);
            let same = rank(b) == rank(&a) && b.label == a.label && contains(b, &a) && contains(&a, b);
            let near_copy = b.label == a.label && b.displacement + 0.05 < a.displacement && overlaps(b, &a);
            larger || same || near_copy
        });
        if !redundant {
            kept.push(a);
        }
    }
    *candidates = kept;
}

/// Whether the main axes (or, without one, the planes) of the two lie
/// within ~10 degrees of each other.
fn overlaps(a: &Candidate, b: &Candidate) -> bool {
    let lines = |c: &Candidate| -> Vec<DVec3> {
        let axes: Vec<DVec3> = c.elements.iter().filter_map(|e| if let Element::Axis { direction, .. } = e { Some(*direction) } else { None }).collect();
        if axes.is_empty() { c.elements.iter().filter_map(|e| if let Element::Plane { normal } = e { Some(*normal) } else { None }).collect() } else { axes }
    };
    let (la, lb) = (lines(a), lines(b));
    !la.is_empty() && la.iter().all(|u| lb.iter().any(|v| u.dot(*v).abs() > 0.985))
}

/// Whether every element of `small` is (nearly) one of `big`'s. A linear
/// group's infinite axis holds every rotation about it and every plane
/// through it (and, with the inversion, the perpendicular C2 axes and the
/// plane across it).
fn contains(big: &Candidate, small: &Candidate) -> bool {
    let line = big.elements.iter().find_map(|e| match e {
        Element::Axis { direction, order: 0 } => Some(*direction),
        _ => None,
    });
    if let Some(a) = line {
        let inversion = big.elements.contains(&Element::Inversion);
        return small.elements.iter().all(|e| match e {
            Element::Inversion => inversion,
            Element::Axis { direction, order } => direction.dot(a).abs() > 0.995 || (inversion && *order == 2 && direction.dot(a).abs() < 0.1),
            Element::Plane { normal } => normal.dot(a).abs() < 0.1 || (inversion && normal.dot(a).abs() > 0.995),
        });
    }
    small.elements.iter().all(|e| {
        big.elements.iter().any(|f| match (e, f) {
            (Element::Inversion, Element::Inversion) => true,
            (Element::Plane { normal: a }, Element::Plane { normal: b }) => a.dot(*b).abs() > 0.995,
            (Element::Axis { direction: a, order: m }, Element::Axis { direction: b, order: n }) => a.dot(*b).abs() > 0.995 && (*n == 0 || (*m != 0 && n % m == 0)),
            _ => false,
        })
    })
}

